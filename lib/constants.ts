export const formatDeadline = (raw: string) => {
  const match = raw.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) return null;
  const [, y, m, d] = match;
  if (m === "00" || d === "00") return null;
  return `${Number(m)}월 ${Number(d)}일`;
};
